"""Generate core/src/data.rs.

Sources (cached in tools/.cache): Tanzil quran-data.js (surahs, juz, pages, rub', sajdah, manzil),
quran.com API verse metadata in quran-com/ (ruku'), and quran.com word line numbers in lines/.
Run: python tools/gen_data.py > core/src/data.rs
"""
import json, os, re, sys

CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")


def quran_com_ruku():
    out = []
    for s in range(1, 115):
        prev = None
        for v in json.load(open(os.path.join(CACHE, "quran-com", f"{s}.json")))["verses"]:
            if v["ruku_number"] != prev:
                out.append((s, v["verse_number"]))
                prev = v["ruku_number"]
    return out


t=open(os.path.join(CACHE,'quran-data.js'),encoding='utf-8').read()
def block(name):
    m=re.search(r'QuranData\.'+name+r'\s*=\s*\[(.*?)\n\];',t,re.S); return m.group(1)
sura=re.findall(r"\[(\d+), (\d+), (\d+), (\d+), '([^']*)', \"([^\"]*)\", '([^']*)', '(\w+)'\]",block('Sura'))
pairs=lambda b:[(int(a),int(c)) for a,c in re.findall(r'\[(\d+), (\d+)\]',b)]
juz=pairs(block('Juz')); page=pairs(block('Page')); rub=pairs(block('HizbQaurter')); ruku=quran_com_ruku()
sajda=re.findall(r"\[(\d+), (\d+), '(\w+)'\]",block('Sajda'))
o=["// Generated by tools/gen_data.py from Tanzil Quran metadata (tanzil.net, CC BY 3.0); ruku' from the quran.com API.",""]
o.append(f"pub const SURAHS: [(&str, &str, u16, bool); {len(sura)}] = [")
for s in sura: o.append(f'    ("{s[4]}", "{s[5]}", {s[1]}, {"true" if s[7]=="Meccan" else "false"}),')
o.append("];");o.append("")
for n,l in (("JUZ",juz),("PAGES",page),("RUB",rub),("RUKU",ruku)):
    o.append(f"pub const {n}: [(u8, u16); {len(l)}] = [");o.append("    "+", ".join(f"({a}, {b})" for a,b in l)+",");o.append("];");o.append("")
o.append(f"pub const SAJDAH: [(u8, u16, bool); {len(sajda)}] = [")
o.append("    "+", ".join(f"({a}, {b}, {'true' if c=='obligatory' else 'false'})" for a,b,c in sajda)+",");o.append("];")
print("\n".join(o))
print(len(sura),len(juz),len(page),len(sajda),sum(int(s[1]) for s in sura),file=sys.stderr)
vdir = os.path.join(CACHE, 'lines')
lines = []
for a, b in rub[:240]:
    w = json.load(open(os.path.join(vdir, f"{a}_{b}.json")))["verse"]["words"][0]
    lines.append((w["page_number"], w["line_number"]))
first = [max(w["line_number"] for v in json.load(open(os.path.join(vdir, f"page{p}.json")))["verses"] for w in v["words"]) for p in (1, 2)]
manzil = [int(s) for s, a in pairs(block('Manzil'))[:7]]
print()
print("// Line data (page, line of first word) from api.quran.com, Madani 15-line layout.")
print(f"pub const RUB_LINES: [(u16, u8); 240] = [")
print("    " + ", ".join(f"({p}, {l})" for p, l in lines) + ",")
print("];")
print()
print(f"pub const FIRST_PAGE_LINES: [u8; 2] = [{first[0]}, {first[1]}];")
print()
print(f"pub const MANZIL: [(u8, char); 7] = [" + ", ".join(f"({s}, '{c}')" for s, c in zip(manzil, "فميبشوق")) + "];")
print(manzil, first, lines[:3], file=sys.stderr)
