"""Generate core/src/data.rs from the quran.com API cache (run tools/fetch_quran_com.sh first).

Run: python tools/gen_data.py > core/src/data.rs
"""
import json
import pathlib

CACHE = pathlib.Path(__file__).resolve().parent / ".cache" / "quran-com"
MANZIL_LETTERS = "فميبشوق"
# The Madani mushaf also marks a sajdah at 22:77 (counted by the Shafi'i and Hanbali schools);
# quran.com lists 14 sajdahs without it, so it is added here and flagged as not in quran.com's list.
EXTRA_SAJDAH = [(22, 77)]


def load():
    chapters = json.loads((CACHE / "chapters.json").read_text())["chapters"]
    verses = [v for s in range(1, 115) for v in json.loads((CACHE / f"{s}.json").read_text())["verses"]]
    return chapters, verses


def key(v):
    s, a = v["verse_key"].split(":")
    return int(s), int(a)


def starts(verses, field):
    out, prev = [], None
    for v in verses:
        if v[field] != prev:
            out.append(v)
            prev = v[field]
    return out


def first_line(v):
    words = [w for w in v["words"] if w["char_type_name"] == "word"]
    return words[0]["page_number"], words[0]["line_number"]


def pairs(name, items, sentinel=True):
    rows = [f"({s}, {a})" for s, a in items] + (["(115, 1)"] if sentinel else [])
    return [f"pub const {name}: [(u8, u16); {len(rows)}] = [", "    " + ", ".join(rows) + ",", "];", ""]


def main():
    chapters, verses = load()
    out = ["// Generated by tools/gen_data.py from the quran.com API (api.quran.com).", ""]
    out.append(f"pub const SURAHS: [(&str, &str, u16, bool); {len(chapters)}] = [")
    for c in chapters:
        out.append(f'    ("{c["name_arabic"]}", "{c["name_simple"]}", {c["verses_count"]}, {"true" if c["revelation_place"] == "makkah" else "false"}),')
    out += ["];", ""]
    out += pairs("JUZ", [key(v) for v in starts(verses, "juz_number")])
    out += pairs("PAGES", [key(v) for v in starts(verses, "page_number")])
    rub = starts(verses, "rub_el_hizb_number")
    out += pairs("RUB", [key(v) for v in rub])
    out += pairs("RUKU", [key(v) for v in starts(verses, "ruku_number")], sentinel=False)
    sajdah = sorted([(key(v), True) for v in verses if v["sajdah_number"]] + [(k, False) for k in EXTRA_SAJDAH])
    out.append(f"/// (surah, ayah, listed by quran.com)")
    out.append(f"pub const SAJDAH: [(u8, u16, bool); {len(sajdah)}] = [")
    out.append("    " + ", ".join(f"({s}, {a}, {'true' if listed else 'false'})" for (s, a), listed in sajdah) + ",")
    out += ["];", ""]
    out.append("/// (page, line of the first word) for each rub' start, Madani 15-line layout.")
    out.append(f"pub const RUB_LINES: [(u16, u8); {len(rub)}] = [")
    out.append("    " + ", ".join("({}, {})".format(*first_line(v)) for v in rub) + ",")
    out += ["];", ""]
    first_pages = [max(w["line_number"] for v in verses for w in v["words"] if w["page_number"] == p) for p in (1, 2)]
    out += [f"pub const FIRST_PAGE_LINES: [u8; 2] = [{first_pages[0]}, {first_pages[1]}];", ""]
    manzil = [key(v)[0] for v in starts(verses, "manzil_number")]
    out.append(f"pub const MANZIL: [(u8, char); {len(manzil)}] = [" + ", ".join(f"({s}, '{c}')" for s, c in zip(manzil, MANZIL_LETTERS)) + "];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
