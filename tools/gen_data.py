"""Generate core/src/data.rs from the Quran Foundation Content Sync snapshots (tools/sync_qf.py).

Page and line numbers follow mushaf 1 (QCF V2, King Fahd Complex 1441 AH print).
Run: python tools/gen_data.py > core/src/data.rs
"""
from qf import quran

MANZIL_LETTERS = "فميبشوق"
# The Madani mushaf also marks a sajdah at 22:77 (counted by the Shafi'i and Hanbali schools);
# quran.com lists 14 sajdahs without it, so it is added here and flagged as not in quran.com's list.
EXTRA_SAJDAH = [(22, 77)]


def starts(verses, field):
    out, prev = [], None
    for v in verses:
        if v[field] != prev:
            out.append(v)
            prev = v[field]
    return out


def pairs(name, items, sentinel=True):
    rows = [f"({s}, {a})" for s, a in items] + (["(115, 1)"] if sentinel else [])
    return [f"pub const {name}: [(u8, u16); {len(rows)}] = [", "    " + ", ".join(rows) + ",", "];", ""]


def main():
    q = quran()
    verses = q.verses
    out = ["// Generated by tools/gen_data.py from Quran Foundation Content Sync (quran_core:1, mushafs:1).", ""]
    out += [f'pub const DATA_FETCHED: &str = "{q.synced}";', ""]
    out.append(f"pub const SURAHS: [(&str, &str, u16, bool); {len(q.chapters)}] = [")
    for c in q.chapters:
        out.append(f'    ("{c["name_arabic"]}", "{c["name_simple"]}", {c["verses_count"]}, {"true" if c["revelation_place"] == "makkah" else "false"}),')
    out += ["];", ""]
    out += pairs("JUZ", [v["key"] for v in starts(verses, "juz_number")])
    out += pairs("PAGES", [v["key"] for v in starts(verses, "page")])
    rub = starts(verses, "rub_el_hizb_number")
    out += pairs("RUB", [v["key"] for v in rub])
    out += pairs("RUKU", [v["key"] for v in starts(verses, "ruku_number")], sentinel=False)
    sajdah = sorted([(v["key"], True) for v in verses if v["sajdah_number"]] + [(k, False) for k in EXTRA_SAJDAH])
    out.append("/// (surah, ayah, listed by quran.com)")
    out.append(f"pub const SAJDAH: [(u8, u16, bool); {len(sajdah)}] = [")
    out.append("    " + ", ".join(f"({s}, {a}, {'true' if listed else 'false'})" for (s, a), listed in sajdah) + ",")
    out += ["];", ""]
    out.append("/// (page, line of the first word) for each rub' start, 15-line Madani layout.")
    out.append(f"pub const RUB_LINES: [(u16, u8); {len(rub)}] = [")
    out.append("    " + ", ".join(f"({v['page']}, {v['line']})" for v in rub) + ",")
    out += ["];", ""]
    out += [f"pub const FIRST_PAGE_LINES: [u8; 2] = [{q.page_lines[1]}, {q.page_lines[2]}];", ""]
    manzil = [v["key"][0] for v in starts(verses, "manzil_number")]
    out.append(f"pub const MANZIL: [(u8, char); {len(manzil)}] = [" + ", ".join(f"({s}, '{c}')" for s, c in zip(manzil, MANZIL_LETTERS)) + "];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
